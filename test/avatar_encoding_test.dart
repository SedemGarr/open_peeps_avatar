const _simpleShuffleRules = AvatarUnlockRules(
  outfits: {
    'Fur Jacket': 26,
    'Thunder T-Shirt': 11,
    'Gaming': 33,
    'Killer': 32,
  },
  poses: {
    'robot_dance-1': 15,
    'robot_dance-2': 15,
    'robot_dance-3': 15,
    'bike': 37,
    'one_leg_up-1': 25,
    'one_leg_up-2': 25,
  },
  inks: {3: 23, 4: 20},
  backgrounds: {4: 2},
  patterns: {1: 12, 2: 24, 3: 35},
);

void main() {
  setUp(() => AvatarUnlocks.configure(_simpleShuffleRules));
  tearDown(() => AvatarUnlocks.configure(AvatarUnlockRules.none));

  test('stored avatars decode to the same look', () {
    for (final f in _fixtures) {
      final look = AvatarLook.decode(f.$1);
      final got = (
        f.$1,
        look.peep.head.name,
        look.peep.face.name,
        look.peep.facialHair.name,
        look.peep.accessory.name,
        look.skin,
        look.ink,
        look.outfitAtom.name,
        look.poseEntry.atom.name,
        look.background,
        look.pattern,
      );
      expect(got, f);
      expect(look.encode(), f.$1);
    }
  });

  test('encode/decode round-trips every option', () {
    for (var i = 0; i < 200; i++) {
      final look = const AvatarLook(
        head: 0,
        face: 0,
        facialHair: 0,
        accessory: 0,
      ).shuffled(Random(i));
      expect(AvatarLook.decode(look.encode()), look);
    }
  });

  test('free picks skip locked outfits and poses', () {
    for (var i = 0; i < 300; i++) {
      final look = const AvatarLook(
        head: 0,
        face: 0,
        facialHair: 0,
        accessory: 0,
      ).shuffled(Random(i)).copyWith(outfit: 0, pose: 0);
      expect(
        AvatarUnlocks.rules.outfits.keys,
        isNot(contains(look.outfitAtom.name)),
      );
      expect(
        AvatarUnlocks.rules.poses.keys,
        isNot(contains(look.poseEntry.atom.name)),
      );
    }
  });
}
